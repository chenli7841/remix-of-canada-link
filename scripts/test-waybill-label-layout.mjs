import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import ts from 'typescript';
const source = fs.readFileSync('src/lib/label-render.ts','utf8').replace(/^import .*;\r?\n/gm,'');
const js = ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
let html='';
const context={exports:{},getDefaultLabelSize:()=> '150x100',window:{open:()=>({document:{open(){},write(value){html=value},close(){}}})}};
vm.runInNewContext(js,context);
const input={entityType:'forwarding',entityNo:'FWHP018731015123',parent:{created_at:'2026-10-15T12:00:00Z',tracking_no:'PARENT123'},user:{customer_code:'01873'},address:{destination_code:'TOR',recipient:'Test',line1:'123 Example Street'},waybills:[{waybill_no:'SCC001',domestic_tracking_no:'JD012345678901',piece_index:2}],total:3};
context.exports.renderLabel(input);
assert.ok(html.includes('<b>2/3</b>'));
assert.ok(html.includes('<strong>261015123</strong>'));
assert.ok(html.includes('JD012345678901'));
assert.ok(!html.includes('PARENT123'));
assert.ok(!html.includes('<span class="muted">客户号</span>'));
assert.ok(!html.includes('<span class="muted">目的地</span>'));
assert.ok(html.includes('full-address'));
assert.ok(html.includes('共 1 张面单'));
input.waybills=[{waybill_no:'SCC001'},{waybill_no:'SCC002'},{waybill_no:'SCC003'}];
context.exports.renderLabel(input);
assert.ok(html.includes('共 3 张面单'));
for(const n of [1,2,3]) assert.ok(html.includes(`<b>${n}/3</b>`));
assert.ok(html.includes('PARENT123'));
context.exports.renderLabel({entityType:'carton',entityNo:'BOX001',meta:{destination_code:'TOR',customer_code:'01873'}});
assert.ok(!html.includes('<div class="customer-main shipping-mark">'));
console.log('Label data checks passed: domestic number, sibling sequence, counts, header and container isolation.');
